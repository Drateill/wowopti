export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = DICTS[lang][key] ?? fr[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useI18n() {
  const { state } = useStore();
  const lang = state.lang;
  return {
    lang,
    t: (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    /** Choisit la version localisée d'un nom venant des données du jeu. */
    L: (v: Localized | undefined) => (v ? v[lang] || v.en : ''),
    stat: (k: keyof Stats) => STAT_NAMES[lang][k],
    slot: (k: string) => SLOT_NAMES[lang][k] ?? k,
    pet: (k: string) => PET_NAMES[lang][k] ?? k,
    num: (n: number, d = 0) => n.toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-US', { minimumFractionDigits: d, maximumFractionDigits: d }),
  };
}
